// Русская типографика для лендинга /phuket-partners.
//
// Автоперенос по ширине оставлял в конце строк висячие предлоги, отрывал
// число от того, что оно считает («17 / августа»), и уносил тире в начало
// следующей строки. Всё это лечится неразрывными пробелами в местах, где
// разрыв запрещён; смысловые переносы заголовков задаются отдельно —
// массивом строк в _content.ts.

const NBSP = ' '

/**
 * Расставляет неразрывные пробелы по трём правилам русского набора.
 * Функция чистая и идемпотентная: повторный прогон ничего не меняет,
 * потому что заменяются только обычные пробелы.
 */
export function typo(text: string): string {
  return (
    text
      // 1. Слова в одну-две буквы (предлоги, союзы, частицы) не висят
      //    в конце строки. Lookbehind не съедает разделитель, поэтому
      //    подряд идущие короткие слова обрабатываются за один проход.
      .replace(/(?<=^|[\s(«„])([A-Za-zА-Яа-яЁё]{1,2}) +/g, `$1${NBSP}`)
      // 2. Число не отрывается от того, что считает: «2 дня», «17 августа»,
      //    «0,5% сверху». Процент и плюс остаются частью числа.
      .replace(/(\d+(?:[.,]\d+)?[%+]?) +(?=[A-Za-zА-Яа-яЁё])/g, `$1${NBSP}`)
      // 3. Тире не начинает строку — уходит на предыдущую вместе с пробелом.
      .replace(/ +—/g, `${NBSP}—`)
  )
}
