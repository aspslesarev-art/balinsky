// Одна вилла — один адрес.
//
// Слаг виллы собирается из «проект + площадь + спальни», поэтому шесть
// одинаковых по планировке юнитов одного проекта получают один и тот же
// адрес. На 16.09.2026 это 371 опубликованная вилла на 309 адресах: 62
// объявления без собственной страницы. Каталог при этом рисовал карточку
// каждому — главная коммерческая страница /ru/villy показывала одну и ту
// же виллу трижды в первых двенадцати карточках, а её ItemList-разметка
// повторяла один и тот же URL. Клик по карточке за 150 000 $ открывал
// соседний юнит за 170 000 $.
//
// У апартаментов это решено в airtable-синхронизации: там каждому слагу
// дописывается -1, -2, …, а прежний лежит в `_slug_alias`. У вилл такой
// синхронизации больше нет (парсеры Airtable удалены), и переименовать
// все 296 уже проиндексированных адресов было бы прямым убытком. Поэтому
// суффикс раздаётся здесь, на чтении, и только «лишним»: первая вилла в
// группе оставляет голый слаг, остальные становятся …-2, …-3.
//
// Порядок внутри группы — по Name, затем по id записи: оба значения не
// меняются между синхронизациями, так что адрес юнита не перескочит на
// соседний при следующей загрузке.
//
// Функцию обязаны звать все потребители — карточки каталога, карта сайта
// и индекс детальных страниц (scripts/sync-detail-indexes.mjs повторяет
// эту же логику на чистом JS). Иначе трое разойдутся в том, кому
// принадлежит голый слаг.

import { normalizeSlug } from '@/lib/slug-normalize'

export type VillaSlugSource = {
  id: string
  /** Сырое значение SEO:Slug — нормализуем сами. */
  slug: string | null
  /** Airtable Name («V00372») — ключ сортировки внутри группы. */
  name: string | null
}

/**
 * Считает финальный слаг каждой виллы.
 *
 * Вход — все ОПУБЛИКОВАННЫЕ виллы без каких-либо других фильтров.
 * Каталог прячет объекты скрытых застройщиков, индекс детальных страниц
 * их оставляет; если посчитать суффиксы на разных наборах, один и тот же
 * юнит получит -2 в каталоге и -3 в индексе, и ссылка приведёт не туда.
 *
 * @returns id записи → слаг. Вилла без пригодного слага в карту не попадает.
 */
export function assignVillaSlugs(rows: readonly VillaSlugSource[]): Map<string, string> {
  const groups = new Map<string, VillaSlugSource[]>()
  for (const r of rows) {
    const base = normalizeSlug(r.slug ?? '')
    if (!base || base.startsWith('-')) continue
    const g = groups.get(base)
    if (g) g.push(r)
    else groups.set(base, [r])
  }

  // Суффикс не должен налететь на чужой настоящий слаг: у группы `foo`
  // второй юнит просится в `foo-2`, а `foo-2` вполне может быть слагом
  // совсем другой виллы.
  const taken = new Set(groups.keys())
  const out = new Map<string, string>()

  for (const [base, group] of [...groups].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    if (group.length === 1) {
      out.set(group[0].id, base)
      continue
    }
    const ordered = [...group].sort((a, b) =>
      (a.name ?? '').localeCompare(b.name ?? '', 'ru') || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    out.set(ordered[0].id, base)
    let n = 2
    for (const r of ordered.slice(1)) {
      let candidate = `${base}-${n}`
      while (taken.has(candidate)) candidate = `${base}-${++n}`
      taken.add(candidate)
      out.set(r.id, candidate)
      n++
    }
  }
  return out
}
