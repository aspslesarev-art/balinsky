// следующий шаг и что написать. Собрано вручную по всей переписке бота
// (tg_messages) с 1 сентября по 5 октября, включая расшифровки голосовых
// и вложения (PDF, видео). Без
// ИИ-сервисов — прочитано и разобрано в сессии Claude Code.
//
// Галочки хранятся в plan_tasks под id задачи (ppl:…), поэтому id менять
// нельзя — отметка держится за него. Новую задачу — с новым id.
//
// Файл импортирует клиентский компонент: никаких серверных зависимостей.

import { HQ_TASK_IDS } from './hq'

export type PersonKind = 'agent' | 'developer' | 'client' | 'team' | 'other'

export type PersonTask = {
  id: string
  text: string
  /** me — обещал или должен сделать Андрей; them — ждём от человека. */
  who: 'me' | 'them'
  /** Срок, если о нём договорились или он очевиден (день по Бали). */
  due?: string
}

/**
 * Сколько денег стоит человек. usd — сумма из переписки (не оценка «на глаз»);
 * null — деньги возможны, но сумма ещё не названа. Порядок (решение Андрея
 * 5.10): сначала ежемесячный фикс застройщиков — он даёт работать с агентами
 * спокойно, — потом разовые деньги со сделок, потом возможные деньги.
 */
export type Money = { usd: number | null; per?: 'month' | 'deal'; label: string }

export type Person = {
  chat: number | null
  name: string
  username: string | null
  kind: PersonKind
  /** Кто это, в двух словах. */
  about: string
  /** На чём остановились. */
  status: string
  /** Один следующий шаг — что сделать, чтобы разговор пошёл дальше. */
  next: string
  /** Готовый текст сообщения в стиле Андрея — скопировать и отправить. */
  draft?: string
  /** Деньги — главный приоритет: по ним сортируется вкладка «По людям». */
  money?: Money
  tasks: PersonTask[]
}

/** Кому писали первыми — ответа нет. Задача одна: дожать или отпустить. */
export type Silent = { chat: number; name: string; username: string | null; kind: PersonKind; sent: string }

/** Разговор закрыт — задач нет. Показаны, чтобы было видно: никто не забыт. */
export type Closed = { chat: number; name: string; username: string | null; kind: PersonKind; why: string }

