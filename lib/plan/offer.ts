/**
 * Страховка поверх промпта: модель всё равно иногда ставит длинные тире
 * и «ёлочки» — Андрей так не пишет.
 */
export function humanize(text: string): string {
  return text
    .replace(/\s*[—–]\s*/g, ' - ')
    .replace(/[«»„“”]/g, '')
    .replace(/!+/g, '.')
    .replace(/\.\./g, '.')
    .replace(/[ \t]+\n/g, '\n')
    .replace(/ {2,}/g, ' ')
    .trim()
}
