// ждущие ответа, просроченные обещания) экран считает сам, а здесь —
// то, что собирает Claude по переписке при каждом обновлении: фокус дня,
// проекты с этапами, разбор работы.
//
// Обновляется в сессии Claude Code по просьбе «обнови штаб» — без
// ИИ-сервисов. Id задач фокуса уникальны для дня (ppl:hq:<день>:<n>),
// галочки лежат в plan_tasks вместе с договорённостями по людям.
//
// Файл импортирует клиентский компонент: никаких серверных зависимостей.

export const HQ_AS_OF = '2026-10-05'

export type FocusItem = {
  id: string
  text: string
  /** Почему это важно — одна фраза. */
  why: string
  level: 'main' | 'second'
  due?: string
}

export type Stage = { text: string; done: boolean }

export type Project = {
  key: string
  title: string
  /** Дата, к которой всё должно сойтись. */
  date: string | null
  /** Зачем проект — одна фраза. */
  goal: string
  stages: Stage[]
  /** Что сейчас мешает или решает. */
  now: string
  /** Проект встречи: гости считаются живыми из разбора переписки. */
  event?: { target: number }
}

export type Review = { period: string; good: string[]; bad: string[]; improve: string[] }

