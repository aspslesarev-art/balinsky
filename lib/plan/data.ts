export type PlanTask = {
  /** `w<неделя>d<день>t<задача>` — по нему хранится галочка. */
  id: string
  text: string
  /** Сумма в долларах: попадает в счётчик денег, когда задача отмечена. */
  amount?: number
  /** Задача — закрытая сделка: идёт в счётчик сделок. */
  deal: boolean
  /** Какой навык качает эта работа. */
  skill: Skill
  /** Опыт за выполнение. */
  xp: number
  /**
   * Задача ждёт чужого решения: подпись застройщика, деньги на счёт,
   * бронь клиента. Такие не стоят в дне — их нельзя «сделать» по
   * расписанию, можно только дожимать. Живут в блоке «В работе».
   */
  waiting: boolean
  /** День, в котором событие ожидалось по плану. */
  expected: string
}

export type PlanDay = { id: string; label: string; iso: string; tasks: PlanTask[] }
export type PlanWeek = { n: number; title: string; dates: string; days: PlanDay[] }

/**
 * Сделка — только пришедшая комиссия: она и есть закрытая сделка.
 * Опознаём по формулировке, поэтому её нельзя менять, не поправив это.
 */
const DEAL_RE = /^Комиссия по Сделке №\d+/

export const PLAN: PlanWeek[] = RAW.map(w => ({
  n: w.n,
  title: w.t,
  dates: w.d,
  days: w.days.map((day, di) => ({
    id: `w${w.n}d${di}`,
    label: day.d,
    iso: day.iso,
    tasks: day.x.map(task => ({
      id: task.id,
      text: task.t,
      amount: task.m,
      deal: DEAL_RE.test(task.t),
      skill: task.s,
      xp: task.xp,
      waiting: task.w === true,
      expected: day.iso,
    })),
  })),
}))

/** Все задачи плана одним списком — для счётчиков и проверки task_id. */
export const ALL_TASKS: PlanTask[] = PLAN.flatMap(w => w.days.flatMap(d => d.tasks))

/** Весь опыт плана по навыкам — «потолок», до которого можно дорасти. */
export const SKILL_TOTALS: Record<Skill, number> = SKILL_ORDER.reduce((acc, sk) => {
  acc[sk] = ALL_TASKS.filter(t => t.skill === sk).reduce((sum, t) => sum + t.xp, 0)
  return acc
}, {} as Record<Skill, number>)

/** Все живые встречи — из них собирается ачивка «Дюжина встреч». */
const COFFEE_IDS: string[] = ALL_TASKS.filter(t => t.text.startsWith('Встреча за кофе')).map(t => t.id)

/** Твои действия — то, что стоит в днях. */
export const ACTION_TASKS: PlanTask[] = ALL_TASKS.filter(t => !t.waiting)

/** Ожидания чужого решения, по плановой дате. */
export const WAITING_TASKS: PlanTask[] = ALL_TASKS
  .filter(t => t.waiting)
  .sort((a, b) => a.expected.localeCompare(b.expected))

const TASK_IDS = new Set(ALL_TASKS.map(t => t.id))

/** Знает ли план такую задачу. API не пишет в базу чужие id. */
export function isKnownTask(id: string): boolean {
  return TASK_IDS.has(id)
}
