// Пошаговая съёмка видеообзора объекта: 3 типа × 4 этапа = 12 сценариев по 15 кадров.
// Источник — раскадровка в Claude Design (Storyboard.dc.html), тексты один в один.
// Закрытая страница /syomka/<ключ>, см. lib/syomka/access.ts.

export type ObjType = 'villa' | 'town' | 'apt'
export type Stage = 'presale' | 'offplan' | 'build' | 'ready'
export type Src = 'real' | 'render' | 'data'
export type Move = 'walk' | 'pan' | 'tilt' | 'still'

export interface Shot {
  n: number
  block: string
  time: string
  kind: string
  src: Src
  size: string
  angle: string
  move: Move
  left: string
  right: string
  shoot: string
  voice: string
  screen: string
  why: string
  /** false — кадр собираю я (картинка застройщика или цифры), снимать не нужно. */
  film: boolean
}

export interface Scenario {
  title: string
  desc: string
  typeNote: string
  shots: Shot[]
}

export const TYPES: { id: ObjType; name: string; hint: string }[] = [
  { id: 'villa', name: 'Вилла', hint: 'Отдельный дом, свой участок' },
  { id: 'town', name: 'Таунхаус', hint: 'Дома в ряд, общие стены' },
  { id: 'apt', name: 'Апартаменты', hint: 'Квартира в общем доме' },
]

export const STAGES: { id: Stage; name: string; hint: string }[] = [
  { id: 'presale', name: 'Пресейл', hint: 'Только участок и картинки. Разрешения часто ещё нет' },
  { id: 'offplan', name: 'Офф-план', hint: 'Продажи идут, стройка только начинается' },
  { id: 'build', name: 'Стройка', hint: 'Стены уже есть, видно этажи' },
  { id: 'ready', name: 'Готово', hint: 'Можно заехать. Новое или вторичка' },
]

