  5: 'Можно ли жить без машины. Это кусок для отдельного короткого ролика.',
  6: 'Вода, шум и запрет посуточной аренды — самые дорогие ошибки покупателя. За этот кадр нам доверяют.',
  7: 'Показывает, справится ли застройщик, или что именно покупают снаружи.',
