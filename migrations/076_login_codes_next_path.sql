-- Куда вернуть человека после входа.
--
-- Вход начинается на конкретной странице объекта: посетитель упирается в
-- закрытый блок с расчётом доходности и жмёт «Войти». Дальше он уходит в
-- Telegram, и всё, что бот мог ему дать, — четыре цифры, которые надо
-- принести обратно руками. На телефоне обратной дороги фактически нет:
-- браузер остаётся где-то за приложением, и до страницы с полем ввода
-- никто не добирается.
--
-- Поэтому сайт запоминает страницу прямо в строке challenge, а бот
-- присылает ссылку `/auth/<token>?next=<эта страница>` — один тап, и
-- человек снова там, откуда уходил, уже авторизованным.
--
-- Путь, а не полный URL: маршрут `/auth/[token]` пускает только
-- относительные пути того же origin, так что чужой домен сюда не подставить.
alter table public.login_codes
  add column if not exists next_path text;
